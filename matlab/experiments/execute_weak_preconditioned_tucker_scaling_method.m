function [solution, info] = ...
    execute_weak_preconditioned_tucker_scaling_method( ...
        config, problem, method_id, seed, check_it)
%EXECUTE_WEAK_PRECONDITIONED_TUCKER_SCALING_METHOD Run one fixed work case.

if nargin < 5
    check_it = [];
end

N = problem.N;
max_rank_value = N;
maxit = config.maximumIterations;

if method_id == "fixed"
    [solution, info] = tucker_gmres_left_preconditioned_fixed( ...
        problem.A, problem.P, ...
        problem.F, problem.U0, maxit, ...
        config.internalStoppingTolerance, ...
        config.fixed_tol, ...
        problem.trueResidualFunction, ...
        problem.precond_residual, false, ...
        config.maximumTuckerBasisEntries, max_rank_value, ...
        check_it);
    return
end

if method_id == "relaxed"
    [solution, info] = ...
        tucker_gmres_left_preconditioned_capped_relaxed( ...
        problem.A, problem.P, ...
        problem.F, problem.U0, maxit, ...
        config.internalStoppingTolerance, ...
        config.relax_budget, ...
        config.max_relax_tol, ...
        problem.trueResidualFunction, ...
        problem.precond_residual, false, ...
        config.maximumTuckerBasisEntries, max_rank_value, ...
        check_it);
    return
end

sketch = create_tucker_row_khatri_rao_sketch( ...
    [N, N, N], config.residualSketchSize, seed);

if method_id == "plain"
    [solution, info] = tucker_sgmres_left_preconditioned_plain( ...
        problem.A_terms, ...
        problem.fixedLinearPreconditionerFunction, ...
        problem.F, problem.U0, maxit, sketch, ...
        config.sketch_tol, ...
        config.ktrunc, ...
        config.plainCompressionTolerance, ...
        config.plainCompressionTolerance, ...
        problem.trueResidualFunction, ...
        problem.precond_residual, false, ...
        config.maximumTuckerBasisEntries, max_rank_value, ...
        check_it);
    return
end

if method_id == "rhosvd_sgmres"
    basis_opts = roundsum_settings( ...
        config, config.basisRoundSumSeedOffset + seed, ...
        config.roundSumCompressionTolerance, max_rank_value);
    solution_opts = roundsum_settings( ...
        config, config.solutionRoundSumSeedOffset + seed, ...
        config.solutionRoundSumTolerance, max_rank_value);
    [solution, info] = tucker_sgmres_left_preconditioned_rhosvd( ...
        problem.A_terms, ...
        problem.fixedLinearPreconditionerFunction, ...
        problem.F, problem.U0, maxit, sketch, ...
        config.sketch_tol, ...
        config.ktrunc, basis_opts, ...
        solution_opts, problem.trueResidualFunction, ...
        problem.precond_residual, false, ...
        config.maximumTuckerBasisEntries, check_it);
    return
end

error('Unknown method identifier %s.', method_id);

end

function settings = roundsum_settings( ...
    config, seed, tolerance, max_rank_value)

settings.compression_tolerance = tolerance;
settings.random_seed = seed;
settings.measure_error_diagnostics = ...
    config.measureRoundSumErrorDiagnostics;
settings.algorithm_variant = "paper_order";
settings.adaptive_rank_selection = true;
settings.oversampling = config.roundSumOversampling;
settings.maximum_rank = max_rank_value;

end
