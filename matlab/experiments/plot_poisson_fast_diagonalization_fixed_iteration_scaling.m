function plot_poisson_fast_diagonalization_fixed_iteration_scaling()
%PLOT_POISSON_FAST_DIAGONALIZATION_FIXED_ITERATION_SCALING Consolidate the four-step study and create its three evidence figures.

experiment_folder = fileparts(mfilename('fullpath'));
matlab_folder = fileparts(experiment_folder);
repository_folder = fileparts(matlab_folder);
processed_folder = fullfile(repository_folder, 'experiments', 'processed');
figure_folder = fullfile(repository_folder, 'experiments', 'figures');

if ~isfolder(figure_folder)
    mkdir(figure_folder);
end

config = ...
    poisson_fast_diagonalization_fixed_iteration_scaling_config();
prefix = char(config.outputPrefix);

all_runs = table();

for N = config.candidateN
    for repeat_index = 1:config.numberOfMeasuredRepeats
        for order_position = 1:3

            method_index = ...
                config.balancedOrder(repeat_index, order_position);
            method_id = char(config.methodIds(method_index));
            case_prefix = sprintf( ...
                '%s_n%d_repeat_%02d_position_%d_method_%s', ...
                prefix, N, repeat_index, order_position, method_id);
            summary_path = fullfile( ...
                processed_folder, [case_prefix, '_summary.csv']);

            assert(isfile(summary_path), ...
                'A protected timing summary is missing: %s', ...
                summary_path);
            next_rows = readtable(summary_path);
            assert(height(next_rows) == 2, ...
                'Each timing case must contain warm-up and measured rows.');
            all_runs = append_table(all_runs, next_rows);

        end
    end
end

all_runs = sortrows( ...
    all_runs, {'N', 'repeat_index', 'order_position', 'measured'});
measured_runs = all_runs(logical(all_runs.measured), :);

expected_measured_runs = ...
    numel(config.candidateN) * ...
    config.numberOfMeasuredRepeats * numel(config.methodIds);

assert(height(measured_runs) == expected_measured_runs, ...
    'The measured table has the wrong number of rows.');
assert(height(all_runs) == 2 * expected_measured_runs, ...
    'The combined table has the wrong number of rows.');
assert(all(measured_runs.iterations == config.maxit), ...
    'Every measured method must complete four Arnoldi steps.');
assert(all(isfinite( ...
    measured_runs.final_original_true_relative_residual)), ...
    'Every measured run must have a finite original residual.');
assert(~any(measured_runs.rank_cap_active), ...
    'A Tucker rank cap became active.');

all_runs_path = fullfile( ...
    processed_folder, [prefix, '_all_runs.csv']);
measured_runs_path = fullfile( ...
    processed_folder, [prefix, '_measured_runs.csv']);
writetable(all_runs, all_runs_path);
writetable(measured_runs, measured_runs_path);

method_summary = table();

for N = config.candidateN
    for method_index = 1:numel(config.methodIds)

        method_rows = measured_runs( ...
            measured_runs.N == N & ...
            measured_runs.method_index == method_index, :);

        assert(height(method_rows) == ...
            config.numberOfMeasuredRepeats, ...
            'Each grid-method pair requires three repetitions.');

        solver_times = method_rows.solver_time_sec;
        final_residuals = ...
            method_rows.final_original_true_relative_residual;
        target_hit = ...
            final_residuals <= config.originalTrueResidualTarget;

        next_row = table( ...
            N, N^config.d, ...
            method_rows.preconditioner_tucker_rank(1), ...
            method_rows.preconditioner_spectral_delta(1), ...
            method_rows.preconditioner_condition_number(1), ...
            method_index, config.methodIds(method_index), ...
            config.methodNames(method_index), ...
            height(method_rows), sum(target_hit), all(target_hit), ...
            median(final_residuals), min(final_residuals), ...
            max(final_residuals), ...
            median(solver_times), min(solver_times), max(solver_times), ...
            median(method_rows.basis_storage_mib), ...
            median(method_rows.maximum_basis_rank, 'omitnan'), ...
            'VariableNames', { ...
                'N', 'number_of_unknowns', ...
                'preconditioner_tucker_rank', ...
                'preconditioner_spectral_delta', ...
                'preconditioner_condition_number', ...
                'method_index', 'method_id', 'method_name', ...
                'number_of_repeats', 'target_hits', ...
                'all_target_hits', ...
                'median_final_original_true_relative_residual', ...
                'minimum_final_original_true_relative_residual', ...
                'maximum_final_original_true_relative_residual', ...
                'median_solver_time_sec', ...
                'minimum_solver_time_sec', ...
                'maximum_solver_time_sec', ...
                'basis_storage_mib', 'maximum_basis_rank'});

        method_summary = append_table(method_summary, next_row);

    end
end

summary_path = fullfile( ...
    processed_folder, [prefix, '_method_summary.csv']);
writetable(method_summary, summary_path);

companion_table = method_summary(:, { ...
    'N', 'number_of_unknowns', 'method_name', ...
    'number_of_repeats', 'target_hits', ...
    'median_final_original_true_relative_residual', ...
    'median_solver_time_sec', 'minimum_solver_time_sec', ...
    'maximum_solver_time_sec', ...
    'basis_storage_mib', 'maximum_basis_rank'});
companion_path = fullfile( ...
    processed_folder, [prefix, '_companion_table.csv']);
writetable(companion_table, companion_path);

% Combine the separately evaluated residual and rank histories

residual_history = table();
rank_history = table();

for N = config.representativeN

    case_prefix = sprintf('%s_n%d_diagnostic', prefix, N);
    residual_path = fullfile( ...
        processed_folder, [case_prefix, '_residual_history.csv']);
    rank_path = fullfile( ...
        processed_folder, [case_prefix, '_rank_history.csv']);

    assert(isfile(residual_path), ...
        'A diagnostic residual history is missing.');
    assert(isfile(rank_path), ...
        'A diagnostic rank history is missing.');

    residual_history = append_table( ...
        residual_history, readtable(residual_path));
    rank_history = append_table(rank_history, readtable(rank_path));

end

assert(all(residual_history.iteration >= 0 & ...
    residual_history.iteration <= config.maxit), ...
    'The residual iteration indices are invalid.');
assert(all(rank_history.iteration >= 0 & ...
    rank_history.iteration <= config.maxit), ...
    'The rank iteration indices are invalid.');

writetable(residual_history, fullfile( ...
    processed_folder, [prefix, '_residual_history.csv']));
writetable(rank_history, fullfile( ...
    processed_folder, [prefix, '_rank_history.csv']));

% Create the residual-versus-iteration figure

S = numerical_plot_style();
method_styles = [ ...
    S.methods.baseline; ...
    S.methods.primary; ...
    S.methods.secondary];

residual_figure = figure('Visible', 'off', 'Color', 'white');
residual_layout = tiledlayout( ...
    residual_figure, 1, numel(config.representativeN), ...
    'TileSpacing', 'compact', 'Padding', 'compact');

for grid_index = 1:numel(config.representativeN)

    N = config.representativeN(grid_index);
    residual_axes = nexttile(residual_layout);
    hold(residual_axes, 'on');

    for method_index = 1:numel(config.methodIds)

        rows = residual_history( ...
            residual_history.N == N & ...
            residual_history.method_index == method_index, :);
        rows = sortrows(rows, 'iteration');
        style = method_styles(method_index);

        semilogy(residual_axes, rows.iteration, ...
            rows.original_true_relative_residual, ...
            'Color', style.color, ...
            'LineStyle', style.line, ...
            'Marker', style.marker, ...
            'MarkerFaceColor', 'white', ...
            'DisplayName', char(config.methodNames(method_index)));

    end

    yline(residual_axes, config.originalTrueResidualTarget, ...
        '--', '$10^{-6}$', ...
        'Color', S.colors.gray, ...
        'HandleVisibility', 'off', ...
        'LabelHorizontalAlignment', 'left');
    set(residual_axes, 'YScale', 'log');
    xlabel(residual_axes, 'Arnoldi iteration $j$');
    title(residual_axes, sprintf('$N=%d$', N));
    xlim(residual_axes, [0, config.maxit]);
    ylim(residual_axes, [1e-10, 2]);
    xticks(residual_axes, 0:config.maxit);

    if grid_index == 1
        ylabel(residual_axes, ...
            '$\Vert b-Ax_j\Vert_2/\Vert b\Vert_2$');
        residual_legend = legend( ...
            residual_axes, 'Orientation', 'horizontal');
        residual_legend.Layout.Tile = 'south';
    end

end

apply_numerical_figure_style( ...
    residual_figure, 'WidthCm', 15.8, 'HeightCm', 6.8);
export_numerical_figure( ...
    residual_figure, fullfile( ...
        figure_folder, [prefix, '_residual_history']), ...
    'WritePNG', true, 'WriteFIG', true);
close(residual_figure);

time_figure = figure('Visible', 'off', 'Color', 'white');
time_axes = axes(time_figure);
hold(time_axes, 'on');

for method_index = 1:numel(config.methodIds)

    rows = method_summary(method_summary.method_index == method_index, :);
    style = method_styles(method_index);
    lower_error = rows.median_solver_time_sec - ...
        rows.minimum_solver_time_sec;
    upper_error = rows.maximum_solver_time_sec - ...
        rows.median_solver_time_sec;

    errorbar(time_axes, rows.N, rows.median_solver_time_sec, ...
        lower_error, upper_error, ...
        'Color', style.color, ...
        'LineStyle', style.line, ...
        'Marker', style.marker, ...
        'MarkerFaceColor', 'white', ...
        'DisplayName', char(config.methodNames(method_index)));

end

set(time_axes, 'YScale', 'log');
xlabel(time_axes, 'Grid size $N$');
ylabel(time_axes, 'Solver time for four Arnoldi steps (s)');
xticks(time_axes, config.candidateN);
legend(time_axes, 'Location', 'northwest');

apply_numerical_figure_style( ...
    time_figure, 'WidthCm', 15.8, 'HeightCm', 8.2);
export_numerical_figure( ...
    time_figure, fullfile( ...
        figure_folder, [prefix, '_solver_time_scaling']), ...
    'WritePNG', true, 'WriteFIG', true);
close(time_figure);

rank_figure = figure('Visible', 'off', 'Color', 'white');
rank_layout = tiledlayout( ...
    rank_figure, 1, numel(config.representativeN), ...
    'TileSpacing', 'compact', 'Padding', 'compact');

for grid_index = 1:numel(config.representativeN)

    N = config.representativeN(grid_index);
    rank_axes = nexttile(rank_layout);
    hold(rank_axes, 'on');

    for method_index = 2:3

        rows = rank_history( ...
            rank_history.N == N & ...
            rank_history.method_index == method_index, :);
        rows = sortrows(rows, 'iteration');
        style = method_styles(method_index);

        plot(rank_axes, rows.iteration, ...
            rows.maximum_basis_rank_to_iteration, ...
            'Color', style.color, ...
            'LineStyle', style.line, ...
            'Marker', style.marker, ...
            'MarkerFaceColor', 'white', ...
            'DisplayName', char(config.methodNames(method_index)));

    end

    xlabel(rank_axes, 'Arnoldi iteration $j$');
    title(rank_axes, sprintf('$N=%d$', N));
    xlim(rank_axes, [0, config.maxit]);
    ylim(rank_axes, [0, 110]);
    xticks(rank_axes, 0:config.maxit);
    yticks(rank_axes, 0:20:100);

    if grid_index == 1
        ylabel(rank_axes, 'Maximum Tucker basis rank');
        rank_legend = legend( ...
            rank_axes, 'Orientation', 'horizontal');
        rank_legend.Layout.Tile = 'south';
    end

end

apply_numerical_figure_style( ...
    rank_figure, 'WidthCm', 15.8, 'HeightCm', 6.8);
export_numerical_figure( ...
    rank_figure, fullfile( ...
        figure_folder, [prefix, '_maximum_rank_history']), ...
    'WritePNG', true, 'WriteFIG', true);
close(rank_figure);

fprintf('Saved timing summary: %s\n', summary_path);
fprintf('Saved companion table: %s\n', companion_path);
fprintf('Saved three fixed-iteration figures with prefix: %s\n', prefix);

end

function output_table = append_table(output_table, next_rows)
%APPEND_TABLE Append rows while preserving the first table's types.

if isempty(output_table)
    output_table = next_rows;
else
    output_table = [output_table; next_rows];
end

end
