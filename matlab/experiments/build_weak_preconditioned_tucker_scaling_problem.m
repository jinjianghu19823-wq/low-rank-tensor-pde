function problem = build_weak_preconditioned_tucker_scaling_problem( ...
    config, N)
%BUILD_WEAK_PRECONDITIONED_TUCKER_SCALING_PROBLEM Build one Poisson case.

h = 1 / (N + 1);
e = ones(N, 1);
A1 = spdiags([-e, 2 * e, -e], ...
    -1:1, N, N) / h^2;
grid_points = (1:N).' / (N + 1);
g = exp( ...
    -config.gaussianExponent * (grid_points - 1/2).^2);
F = ttensor(tensor(1, [1, 1, 1]), ...
    {g, g, g});
U0 = 0 * F;

[preconditioner, preconditioner_info] = ...
    build_poisson_fast_diagonalization_tucker_preconditioner( ...
    A1, config.preconditionerTuckerRank);
if ~preconditioner_info.is_positive_definite
    error('The rank one preconditioner is not positive at N=%d.', N);
end

problem.N = N;
problem.A1 = A1;
problem.F = F;
problem.U0 = U0;
problem.preconditioner = preconditioner;
problem.preconditionerInfo = preconditioner_info;
problem.A = @(U, tolerance, rank_cap) ...
    poisson_action_tucker(U, A1, tolerance, rank_cap);
problem.A_terms = @(U) ...
    poisson_action_tucker_terms(U, A1);
problem.P = @(Y, tolerance, rank_cap) ...
    apply_poisson_fast_diagonalization_tucker_preconditioner( ...
    Y, preconditioner, tolerance, rank_cap);
problem.fixedLinearPreconditionerFunction = @(Y) ...
    apply_poisson_fast_diagonalization_tucker_preconditioner_exact( ...
    Y, preconditioner);
problem.trueResidualFunction = @(U) ...
    true_residual_tucker_poisson(U, F, A1);
problem.precond_residual = @(U) ...
    preconditioned_residual_norm_tucker_poisson_fast_diagonalization( ...
    U, F, A1, preconditioner, config.diagnosticTolerance);

end
