%% Plot-only rebuild for the Section 6.1 three-method GMRES comparison
% This script reads the verified processed CSV files. It does not rerun the
% solvers and therefore does not change the saved residuals or timings.

clear;
clc;
close all;

scriptFolder = fileparts(mfilename('fullpath'));
matlabFolder = fileparts(scriptFolder);
projectFolder = fileparts(matlabFolder);
addpath(fullfile(matlabFolder, 'plotting'));

processedFolder = fullfile(projectFolder, 'experiments', 'processed');
figureFolder = fullfile(projectFolder, 'experiments', 'figures');

historyData = readtable(fullfile(processedFolder, ...
    'gmres_sgmres_poisson_scaling_history_summary.csv'));
runtimeData = readtable(fullfile(processedFolder, ...
    'gmres_sgmres_poisson_scaling_summary.csv'));

NValues = [100, 200, 400, 800, 1000];
numberOfMethods = 3;
numberOfCheckpoints = 14;
assert(height(historyData) == ...
    numel(NValues) * numberOfMethods * numberOfCheckpoints, ...
    'Unexpected number of rows in the residual-history summary.');
assert(height(runtimeData) == numel(NValues) * numberOfMethods, ...
    'Unexpected number of rows in the runtime summary.');
assert(isequal(sort(unique(historyData.N))', NValues), ...
    'Residual data must contain all five requested grid sizes.');
assert(isequal(sort(unique(runtimeData.N))', NValues), ...
    'Runtime data must contain all five requested grid sizes.');
assert(isequal(sort(unique(historyData.method_code)), [1; 2; 3]), ...
    'Residual data must contain method codes 1, 2, and 3.');
assert(isequal(sort(unique(runtimeData.method_code)), [1; 2; 3]), ...
    'Runtime data must contain method codes 1, 2, and 3.');
assert(all(runtimeData.median_runtime_sec > 0), ...
    'All median runtimes must be positive.');

if ~isfolder(figureFolder)
    mkdir(figureFolder);
end

style = numerical_plot_style();
GMRESCode = 1;
sGMRESCode = 2;
restartedGMRESCode = 3;
targetResidual = 1e-6;
positiveResiduals = [historyData.min_true_relres; ...
    historyData.max_true_relres];
positiveResiduals = positiveResiduals(positiveResiduals > 0);
residualLowerLimit = 10^floor(log10(min(positiveResiduals)));

%% True-residual histories at the recorded checkpoints
convergenceFigure = figure('Visible', 'off', 'Color', 'white');
convergenceLayout = tiledlayout(convergenceFigure, 2, 3, ...
    'TileSpacing', 'compact', 'Padding', 'compact');

gmresLegendHandle = gobjects(1);
restartedLegendHandle = gobjects(1);
sgmresLegendHandle = gobjects(1);

for NIndex = 1:numel(NValues)
    N = NValues(NIndex);
    ax = nexttile(convergenceLayout);
    ax.YScale = 'log';
    hold(ax, 'on');

    gmresRows = historyData.N == N & ...
        historyData.method_code == GMRESCode;
    restartedRows = historyData.N == N & ...
        historyData.method_code == restartedGMRESCode;
    sgmresRows = historyData.N == N & ...
        historyData.method_code == sGMRESCode;

    gmresCurve = sortrows(historyData(gmresRows, :), 'iteration');
    restartedCurve = sortrows(historyData(restartedRows, :), 'iteration');
    sgmresCurve = sortrows(historyData(sgmresRows, :), 'iteration');

    plot_uncertainty_band(ax, sgmresCurve.iteration, ...
        sgmresCurve.min_true_relres, sgmresCurve.max_true_relres, ...
        style.methods.primary.color, 'FaceAlpha', 0.13);

    gmresLine = semilogy(ax, gmresCurve.iteration, ...
        gmresCurve.median_true_relres, ...
        'Color', style.methods.baseline.color, ...
        'LineStyle', style.methods.baseline.line, ...
        'Marker', style.methods.baseline.marker, ...
        'LineWidth', style.lineWidth, ...
        'MarkerSize', 3.6, ...
        'DisplayName', 'Unrestarted GMRES');

    restartedLine = semilogy(ax, restartedCurve.iteration, ...
        restartedCurve.median_true_relres, ...
        'Color', style.methods.comparator.color, ...
        'LineStyle', style.methods.comparator.line, ...
        'Marker', style.methods.comparator.marker, ...
        'LineWidth', style.lineWidth, ...
        'MarkerSize', 3.6, ...
        'DisplayName', 'GMRES(50)');

    sgmresLine = semilogy(ax, sgmresCurve.iteration, ...
        sgmresCurve.median_true_relres, ...
        'Color', style.methods.primary.color, ...
        'LineStyle', style.methods.primary.line, ...
        'Marker', style.methods.primary.marker, ...
        'LineWidth', style.lineWidth, ...
        'MarkerSize', 3.6, ...
        'DisplayName', 'sGMRES median');

    yline(ax, targetResidual, style.methods.reference.line, ...
        'Color', style.methods.reference.color, ...
        'LineWidth', style.referenceLineWidth, ...
        'HandleVisibility', 'off');

    title(ax, sprintf('$N=%d$', N), 'Interpreter', 'latex');
    xlim(ax, [0, 250]);
    ylim(ax, [residualLowerLimit, 2]);
    xticks(ax, [0, 50, 100, 150, 200, 250]);
    ax.XTickLabelRotation = 0;

    if NIndex == 1
        gmresLegendHandle = gmresLine;
        restartedLegendHandle = restartedLine;
        sgmresLegendHandle = sgmresLine;
    end
end

xlabel(convergenceLayout, 'Cumulative Arnoldi step $k$', ...
    'Interpreter', 'latex');
ylabel(convergenceLayout, ...
    '$\Vert b-Ax_k\Vert_2/\Vert b\Vert_2$', ...
    'Interpreter', 'latex');

convergenceLegend = legend( ...
    [gmresLegendHandle, restartedLegendHandle, sgmresLegendHandle], ...
    {'Unrestarted GMRES', 'GMRES(50)', 'sGMRES median'}, ...
    'Orientation', 'vertical', 'NumColumns', 1);
convergenceLegend.Layout.Tile = 6;

apply_numerical_figure_style(convergenceFigure, ...
    'WidthCm', 15.8, 'HeightCm', 10.4, 'Grid', true);

export_numerical_figure(convergenceFigure, fullfile( ...
    figureFolder, 'gmres_sgmres_poisson_convergence'), ...
    'WritePNG', true, 'WriteFIG', true);
close(convergenceFigure);

%% Solver times with observed min--max ranges
runtimeFigure = figure('Visible', 'off', 'Color', 'white');
runtimeAxis = axes(runtimeFigure);
runtimeAxis.YScale = 'log';
hold(runtimeAxis, 'on');

gmresRows = runtimeData.method_code == GMRESCode;
restartedRows = runtimeData.method_code == restartedGMRESCode;
sgmresRows = runtimeData.method_code == sGMRESCode;
gmresTimes = sortrows(runtimeData(gmresRows, :), 'N');
restartedTimes = sortrows(runtimeData(restartedRows, :), 'N');
sgmresTimes = sortrows(runtimeData(sgmresRows, :), 'N');

gmresRuntime = errorbar(runtimeAxis, gmresTimes.N, ...
    gmresTimes.median_runtime_sec, ...
    gmresTimes.median_runtime_sec - gmresTimes.min_runtime_sec, ...
    gmresTimes.max_runtime_sec - gmresTimes.median_runtime_sec, ...
    'Color', style.methods.baseline.color, ...
    'LineStyle', style.methods.baseline.line, ...
    'Marker', style.methods.baseline.marker, ...
    'LineWidth', style.lineWidth, ...
    'MarkerSize', style.markerSize, ...
    'CapSize', 5, ...
    'DisplayName', 'Unrestarted GMRES');

restartedRuntime = errorbar(runtimeAxis, restartedTimes.N, ...
    restartedTimes.median_runtime_sec, ...
    restartedTimes.median_runtime_sec - restartedTimes.min_runtime_sec, ...
    restartedTimes.max_runtime_sec - restartedTimes.median_runtime_sec, ...
    'Color', style.methods.comparator.color, ...
    'LineStyle', style.methods.comparator.line, ...
    'Marker', style.methods.comparator.marker, ...
    'LineWidth', style.lineWidth, ...
    'MarkerSize', style.markerSize, ...
    'CapSize', 5, ...
    'DisplayName', 'GMRES(50)');

sgmresRuntime = errorbar(runtimeAxis, sgmresTimes.N, ...
    sgmresTimes.median_runtime_sec, ...
    sgmresTimes.median_runtime_sec - sgmresTimes.min_runtime_sec, ...
    sgmresTimes.max_runtime_sec - sgmresTimes.median_runtime_sec, ...
    'Color', style.methods.primary.color, ...
    'LineStyle', style.methods.primary.line, ...
    'Marker', style.methods.primary.marker, ...
    'LineWidth', style.lineWidth, ...
    'MarkerSize', style.markerSize, ...
    'CapSize', 5, ...
    'DisplayName', 'sGMRES');

xlabel(runtimeAxis, 'Grid parameter $N$', 'Interpreter', 'latex');
ylabel(runtimeAxis, 'Solver time (s)', 'Interpreter', 'latex');
xticks(runtimeAxis, NValues);
xlim(runtimeAxis, [50, 1050]);
allMinimumTimes = [gmresTimes.min_runtime_sec; ...
    restartedTimes.min_runtime_sec; sgmresTimes.min_runtime_sec];
allMaximumTimes = [gmresTimes.max_runtime_sec; ...
    restartedTimes.max_runtime_sec; sgmresTimes.max_runtime_sec];
ylim(runtimeAxis, [0.75 * min(allMinimumTimes), ...
    1.35 * max(allMaximumTimes)]);
legend(runtimeAxis, [gmresRuntime, restartedRuntime, sgmresRuntime], ...
    {'Unrestarted GMRES', 'GMRES(50)', 'sGMRES'}, ...
    'Location', 'northwest');

apply_numerical_figure_style(runtimeFigure, ...
    'WidthCm', 11.4, 'HeightCm', 6.7, 'Grid', true);

export_numerical_figure(runtimeFigure, fullfile( ...
    figureFolder, 'gmres_sgmres_poisson_runtime'), ...
    'WritePNG', true, 'WriteFIG', true);
close(runtimeFigure);

fprintf('Rebuilt the Section 6.1 figures from processed CSV data.\n');
