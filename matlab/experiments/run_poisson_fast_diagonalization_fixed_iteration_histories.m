function run_poisson_fast_diagonalization_fixed_iteration_histories(N)
%RUN_POISSON_FAST_DIAGONALIZATION_FIXED_ITERATION_HISTORIES Reconstruct independent residual histories outside the timing study.

experiment_folder = fileparts(mfilename('fullpath'));
matlab_folder = fileparts(experiment_folder);
repository_folder = fileparts(matlab_folder);
addpath(genpath(matlab_folder));
add_toolboxes();

config = ...
    poisson_fast_diagonalization_fixed_iteration_scaling_config();

if ~isscalar(N) || N ~= round(N) || ...
        ~ismember(N, config.representativeN)
    error('N must be one of the representative diagnostic grid sizes.');
end

processed_folder = fullfile(repository_folder, 'experiments', 'processed');
raw_folder = fullfile(repository_folder, 'experiments', 'raw');

if ~isfolder(processed_folder)
    mkdir(processed_folder);
end

if ~isfolder(raw_folder)
    mkdir(raw_folder);
end

case_prefix = sprintf('%s_n%d_diagnostic', ...
    char(config.outputPrefix), N);
residual_path = fullfile( ...
    processed_folder, [case_prefix, '_residual_history.csv']);
rank_path = fullfile( ...
    processed_folder, [case_prefix, '_rank_history.csv']);
raw_path = fullfile(raw_folder, [case_prefix, '.mat']);

if isfile(residual_path) || isfile(rank_path) || isfile(raw_path)
    error('The protected diagnostic output already exists.');
end

grid_index = find(config.candidateN == N, 1);
preconditioner_rank = config.preconditionerTuckerRanks(grid_index);
h = 1 / (N + 1);
e = ones(N, 1);
A1 = spdiags( ...
    [-e, 2 * e, -e], ...
    -1:1, N, N) / h^2;

grid_points = (1:N).' / (N + 1);
g = exp( ...
    -config.gaussianExponent * (grid_points - 1/2).^2);

[preconditioner, preconditioner_info] = ...
    build_poisson_fast_diagonalization_tucker_preconditioner( ...
        A1, preconditioner_rank);

assert(preconditioner_info.is_positive_definite, ...
    'The selected preconditioner is not positive definite.');
assert(preconditioner_info.spectral_delta <= ...
    config.maximumPreconditionerSpectralDelta, ...
    'The selected preconditioner violates the spectral-quality rule.');

max_rank = ...
    N * ones(1, config.d);

% Evaluate the true original residual after each cycle length

residual_history = table();
rank_history = table();
diagnostic_info = cell(numel(config.methodIds), ...
    config.maxit);

for method_index = 1:numel(config.methodIds)

    method_data = build_method_data( ...
        method_index, config, A1, g, ...
        preconditioner, max_rank);

    initial_residual = initial_original_residual( ...
        method_index, method_data);

    residual_history = append_residual_row( ...
        residual_history, N, method_index, config, ...
        0, initial_residual);

    for cycle_length = 1:config.maxit

        fprintf( ...
            'Diagnostic N=%d, %s, cycle length %d/%d\n', ...
            N, char(config.methodNames(method_index)), ...
            cycle_length, config.maxit);

        info = execute_method( ...
            method_index, cycle_length, config, method_data, ...
            max_rank);
        diagnostic_info{method_index, cycle_length} = info;

        assert(info.iterations == cycle_length, ...
            'A diagnostic cycle ended before its requested length.');

        residual_history = append_residual_row( ...
            residual_history, N, method_index, config, ...
            cycle_length, final_original_residual(method_index, info));

    end

    if method_index > 1

        full_cycle_info = diagnostic_info{ ...
            method_index, config.maxit};
        basis_ranks = full_cycle_info.basis_ranks;

        for iteration = 0:config.maxit

            ranks_available = basis_ranks(1:iteration + 1, :);
            cumulative_maximum_rank = max(ranks_available, [], 'all');
            new_basis_vector_maximum_rank = ...
                max(basis_ranks(iteration + 1, :));

            next_rank_row = table( ...
                N, method_index, config.methodIds(method_index), ...
                config.methodNames(method_index), iteration, ...
                cumulative_maximum_rank, new_basis_vector_maximum_rank, ...
                'VariableNames', { ...
                    'N', 'method_index', 'method_id', 'method_name', ...
                    'iteration', 'maximum_basis_rank_to_iteration', ...
                    'new_basis_vector_maximum_rank'});

            rank_history = append_table(rank_history, next_rank_row);

        end
    end
end

writetable(residual_history, residual_path);
writetable(rank_history, rank_path);
payload.config = config;
payload.N = N;
payload.A1 = A1;
payload.preconditionerInfo = preconditioner_info;
payload.diagnosticInfo = diagnostic_info;
payload.residualHistory = residual_history;
payload.rankHistory = rank_history;
save(raw_path, '-struct', 'payload');

fprintf('Saved diagnostic residual history: %s\n', residual_path);
fprintf('Saved diagnostic rank history: %s\n', rank_path);

end

function method_data = build_method_data( ...
    method_index, config, A1, g, ...
    preconditioner, max_rank)
%BUILD_METHOD_DATA Construct only the representation needed by one method.

N = length(g);

if method_index == 1

    method_data.b = kron( ...
        g, kron(g, g));
    method_data.x0 = zeros(N^3, 1);
    inverse_multiplier = ...
        double(full(preconditioner.inverse_eigenvalue_tensor));
    method_data.operator_function = @(x) ...
        poisson_action_full_vector_3d(x, A1, N);
    method_data.preconditioner_function = @(x) ...
        apply_poisson_fast_diagonalization_full_preconditioner( ...
            x, inverse_multiplier);

else

    method_data.F = ttensor(tensor(1, [1, 1, 1]), ...
        {g, g, g});
    method_data.U0 = 0 * method_data.F;
    method_data.operator_function = @(U, tolerance, max_ranks) ...
        poisson_action_tucker(U, A1, tolerance, max_ranks);
    method_data.preconditioner_function = ...
        @(Y, tolerance, max_ranks) ...
        apply_poisson_fast_diagonalization_tucker_preconditioner( ...
            Y, preconditioner, tolerance, max_ranks);
    method_data.original_residual_function = @(U) ...
        true_residual_tucker_poisson(U, method_data.F, A1);
    method_data.preconditioned_residual_function = @(U) ...
        preconditioned_residual_norm_tucker_poisson_fast_diagonalization( ...
            U, method_data.F, A1, preconditioner, ...
            config.diagnosticTolerance);

end

method_data.maximum_multilinear_rank = max_rank;

end

function info = execute_method( ...
    method_index, cycle_length, config, method_data, ...
    max_rank)
%EXECUTE_METHOD Run one untimed-history diagnostic cycle.

if method_index == 1

    [~, info] = gmres_left_preconditioned_full_fixed_cycle( ...
        method_data.operator_function, ...
        method_data.preconditioner_function, ...
        method_data.b, method_data.x0, ...
        cycle_length, config.originalTrueResidualTarget, false);

elseif method_index == 2

    [~, info] = tucker_gmres_left_preconditioned_fixed( ...
        method_data.operator_function, ...
        method_data.preconditioner_function, ...
        method_data.F, method_data.U0, ...
        cycle_length, ...
        config.internalPreconditionedStoppingTolerance, ...
        config.fixedRecompressionTolerance, ...
        method_data.original_residual_function, ...
        method_data.preconditioned_residual_function, ...
        false, config.maximumTuckerBasisEntries, ...
        max_rank);

else

    [~, info] = tucker_gmres_left_preconditioned_capped_relaxed( ...
        method_data.operator_function, ...
        method_data.preconditioner_function, ...
        method_data.F, method_data.U0, ...
        cycle_length, ...
        config.internalPreconditionedStoppingTolerance, ...
        config.relax_budget, ...
        config.max_relax_tol, ...
        method_data.original_residual_function, ...
        method_data.preconditioned_residual_function, ...
        false, config.maximumTuckerBasisEntries, ...
        max_rank);

end

end

function residual = initial_original_residual(method_index, method_data)
%INITIAL_ORIGINAL_RESIDUAL Evaluate the common initial residual.

if method_index == 1
    residual = norm( ...
        method_data.b - ...
        method_data.operator_function(method_data.x0)) / ...
        norm(method_data.b);
else
    residual = ...
        method_data.original_residual_function(method_data.U0);
end

end

function residual = final_original_residual(method_index, info)
%FINAL_ORIGINAL_RESIDUAL Extract the independent cycle-end value.

if method_index == 1
    residual = info.original_true_relative_residual;
else
    residual = info.true_relative_residual(end);
end

end

function output_table = append_residual_row( ...
    output_table, N, method_index, config, iteration, residual)
%APPEND_RESIDUAL_ROW Add one original-residual observation.

next_row = table( ...
    N, method_index, config.methodIds(method_index), ...
    config.methodNames(method_index), iteration, residual, ...
    'VariableNames', { ...
        'N', 'method_index', 'method_id', 'method_name', ...
        'iteration', 'original_true_relative_residual'});

output_table = append_table(output_table, next_row);

end

function output_table = append_table(output_table, next_row)
%APPEND_TABLE Append while preserving the first row's variable types.

if isempty(output_table)
    output_table = next_row;
else
    output_table = [output_table; next_row];
end

end
