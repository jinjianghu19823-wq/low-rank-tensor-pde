function [solution, info] = ...
    execute_weak_preconditioned_tucker_scaling_method( ...
        config, problem, methodId, seed, diagnosticIterations)
%EXECUTE_WEAK_PRECONDITIONED_TUCKER_SCALING_METHOD Run one fixed work case.

if nargin < 5
    diagnosticIterations = [];
end

N = problem.N;
maximumRank = N;
maximumIteration = config.maximumIterations;

if methodId == "fixed"
    [solution, info] = tucker_gmres_left_preconditioned_fixed( ...
        problem.operatorFunction, problem.preconditionerFunction, ...
        problem.F, problem.U0, maximumIteration, ...
        config.internalStoppingTolerance, ...
        config.fixedCompressionTolerance, ...
        problem.trueResidualFunction, ...
        problem.preconditionedResidualNormFunction, false, ...
        config.maximumTuckerBasisEntries, maximumRank, ...
        diagnosticIterations);
    return
end

if methodId == "relaxed"
    [solution, info] = ...
        tucker_gmres_left_preconditioned_capped_relaxed( ...
        problem.operatorFunction, problem.preconditionerFunction, ...
        problem.F, problem.U0, maximumIteration, ...
        config.internalStoppingTolerance, ...
        config.relaxationErrorBudget, ...
        config.maximumRelaxedTolerance, ...
        problem.trueResidualFunction, ...
        problem.preconditionedResidualNormFunction, false, ...
        config.maximumTuckerBasisEntries, maximumRank, ...
        diagnosticIterations);
    return
end

residualSketch = create_tucker_row_khatri_rao_sketch( ...
    [N, N, N], config.residualSketchSize, seed);

if methodId == "plain"
    [solution, info] = tucker_sgmres_left_preconditioned_plain( ...
        problem.operatorTermsFunction, ...
        problem.fixedLinearPreconditionerFunction, ...
        problem.F, problem.U0, maximumIteration, residualSketch, ...
        config.sketchStoppingTolerance, ...
        config.orthogonalisationWindow, ...
        config.plainCompressionTolerance, ...
        config.plainCompressionTolerance, ...
        problem.trueResidualFunction, ...
        problem.preconditionedResidualNormFunction, false, ...
        config.maximumTuckerBasisEntries, maximumRank, ...
        diagnosticIterations);
    return
end

if methodId == "rhosvd_sgmres"
    basisSettings = roundsum_settings( ...
        config, config.basisRoundSumSeedOffset + seed, ...
        config.roundSumCompressionTolerance, maximumRank);
    solutionSettings = roundsum_settings( ...
        config, config.solutionRoundSumSeedOffset + seed, ...
        config.solutionRoundSumTolerance, maximumRank);
    [solution, info] = tucker_sgmres_left_preconditioned_rhosvd( ...
        problem.operatorTermsFunction, ...
        problem.fixedLinearPreconditionerFunction, ...
        problem.F, problem.U0, maximumIteration, residualSketch, ...
        config.sketchStoppingTolerance, ...
        config.orthogonalisationWindow, basisSettings, ...
        solutionSettings, problem.trueResidualFunction, ...
        problem.preconditionedResidualNormFunction, false, ...
        config.maximumTuckerBasisEntries, diagnosticIterations);
    return
end

error('Unknown method identifier %s.', methodId);

end


function settings = roundsum_settings( ...
    config, seed, tolerance, maximumRank)

settings.compression_tolerance = tolerance;
settings.random_seed = seed;
settings.measure_error_diagnostics = ...
    config.measureRoundSumErrorDiagnostics;
settings.algorithm_variant = "paper_order";
settings.adaptive_rank_selection = true;
settings.oversampling = config.roundSumOversampling;
settings.maximum_rank = maximumRank;

end
