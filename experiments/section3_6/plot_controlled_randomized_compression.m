    tensorData.RSTHOSVD_RelErrMean, tensorData.RSTHOSVD_RelErrStd, ...
    'Color', style.methods.secondary.color, ...
    'LineStyle', style.methods.secondary.line, ...
    'Marker', style.methods.secondary.marker, ...
    'LineWidth', style.lineWidth, ...
    'MarkerSize', style.markerSize, ...
    'CapSize', 3, ...
    'DisplayName', 'RSTHOSVD');

mlnError = errorbar(tensorErrorAxis, rank, ...
    tensorData.MLN_RelErrMean, tensorData.MLN_RelErrStd, ...
    'Color', style.methods.comparator.color, ...
    'LineStyle', style.methods.comparator.line, ...
    'Marker', 'v', ...
    'LineWidth', style.lineWidth, ...
    'MarkerSize', style.markerSize, ...
    'CapSize', 3, ...
    'DisplayName', 'MLN');

xlabel(tensorErrorAxis, 'Multilinear rank $(r,r,r)$', ...
    'Interpreter', 'latex');
ylabel(tensorErrorAxis, ...
    '$\Vert\mathcal X-\widehat{\mathcal X}\Vert_F/\Vert\mathcal X\Vert_F$', ...
    'Interpreter', 'latex');
xticks(tensorErrorAxis, [5, 20, 40, 60, 80]);

tensorTimeAxis = nexttile(tensorLayout);
tensorTimeAxis.YScale = 'log';
hold(tensorTimeAxis, 'on');

plot(tensorTimeAxis, rank, tensorData.HOSVD_Time, ...
    'Color', style.methods.baseline.color, ...
    'LineStyle', style.methods.baseline.line, ...
    'Marker', style.methods.baseline.marker, ...
    'LineWidth', style.lineWidth, ...
    'MarkerSize', style.markerSize, ...
    'DisplayName', 'HOSVD');

errorbar(tensorTimeAxis, rank, ...
    tensorData.RHOSVD_TimeMean, tensorData.RHOSVD_TimeStd, ...
    'Color', style.methods.primary.color, ...
    'LineStyle', style.methods.primary.line, ...
    'Marker', style.methods.primary.marker, ...
    'LineWidth', style.lineWidth, ...
    'MarkerSize', style.markerSize, ...
    'CapSize', 3, ...
    'DisplayName', 'RHOSVD');

plot(tensorTimeAxis, rank, tensorData.STHOSVD_Time, ...
    'Color', style.colors.orange, ...
    'LineStyle', ':', ...
    'Marker', '^', ...
    'LineWidth', style.lineWidth, ...
    'MarkerSize', style.markerSize, ...
    'DisplayName', 'STHOSVD');

errorbar(tensorTimeAxis, rank, ...
    tensorData.RSTHOSVD_TimeMean, tensorData.RSTHOSVD_TimeStd, ...
    'Color', style.methods.secondary.color, ...
    'LineStyle', style.methods.secondary.line, ...
    'Marker', style.methods.secondary.marker, ...
    'LineWidth', style.lineWidth, ...
    'MarkerSize', style.markerSize, ...
    'CapSize', 3, ...
    'DisplayName', 'RSTHOSVD');

errorbar(tensorTimeAxis, rank, ...
    tensorData.MLN_TimeMean, tensorData.MLN_TimeStd, ...
    'Color', style.methods.comparator.color, ...
    'LineStyle', style.methods.comparator.line, ...
    'Marker', 'v', ...
    'LineWidth', style.lineWidth, ...
    'MarkerSize', style.markerSize, ...
    'CapSize', 3, ...
    'DisplayName', 'MLN');

xlabel(tensorTimeAxis, 'Multilinear rank $(r,r,r)$', ...
    'Interpreter', 'latex');
ylabel(tensorTimeAxis, 'Measured time (s)', 'Interpreter', 'latex');
xticks(tensorTimeAxis, [5, 20, 40, 60, 80]);

tensorLegend = legend(tensorErrorAxis, ...
    [hosvdError, rhosvdError, sthosvdError, rsthosvdError, mlnError], ...
    {'HOSVD', 'RHOSVD', 'STHOSVD', 'RSTHOSVD', 'MLN'}, ...
    'Orientation', 'horizontal', 'NumColumns', 5);
tensorLegend.Layout.Tile = 'north';

apply_numerical_figure_style(tensorFigure, ...
    'WidthCm', 15.8, 'HeightCm', 6.4, 'Grid', true);

export_numerical_figure(tensorFigure, fullfile( ...
    figureFolder, 'controlled_tensor_randomized_compression'), ...
    'WritePNG', true, 'WriteFIG', true);
close(tensorFigure);

fprintf('Rebuilt the controlled Section 3.6 figures from processed CSV data.\n');
