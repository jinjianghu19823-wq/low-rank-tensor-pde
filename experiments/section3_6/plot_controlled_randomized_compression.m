%% Plot-only rebuild for the controlled Section 3.6 illustrations
% This script reads the verified processed CSV files. It does not rerun the
% matrix or tensor experiments and therefore does not change their timings.

clear;
clc;
close all;

scriptFolder = fileparts(mfilename('fullpath'));
matlabFolder = fileparts(scriptFolder);
projectFolder = fileparts(matlabFolder);
addpath(projectFolder);
setup();

processedFolder = fullfile(projectFolder, 'experiments', 'processed');
figureFolder = fullfile(projectFolder, 'experiments', 'figures');

matrixData = readtable(fullfile( ...
    processedFolder, 'experiment1_power_decay_results.csv'));
tensorData = readtable(fullfile( ...
    processedFolder, 'experiment2_power_tensor_results.csv'));

assert(height(matrixData) == 6, ...
    'Expected six tested matrix ranks in the processed table.');
assert(height(tensorData) == 6, ...
    'Expected six tested tensor ranks in the processed table.');

if ~isfolder(figureFolder)
    mkdir(figureFolder);
end

style = numerical_plot_style();

%% Matrix: approximation error and directly measured factorisation time
matrixFigure = figure('Visible', 'off', 'Color', 'white');
matrixLayout = tiledlayout(matrixFigure, 1, 2, ...
    'TileSpacing', 'compact', 'Padding', 'compact');

rank = matrixData.Rank;

matrixErrorAxis = nexttile(matrixLayout);
matrixErrorAxis.YScale = 'log';
hold(matrixErrorAxis, 'on');

svdError = plot(matrixErrorAxis, rank, matrixData.SVD_RelErr, ...
    'Color', style.methods.baseline.color, ...
    'LineStyle', style.methods.baseline.line, ...
    'Marker', style.methods.baseline.marker, ...
    'LineWidth', style.lineWidth, ...
    'MarkerSize', style.markerSize, ...
    'DisplayName', 'truncated SVD');

rsvdError = errorbar(matrixErrorAxis, rank, ...
    matrixData.RSVD_RelErrMean, matrixData.RSVD_RelErrStd, ...
    'Color', style.methods.primary.color, ...
    'LineStyle', style.methods.primary.line, ...
    'Marker', style.methods.primary.marker, ...
    'LineWidth', style.lineWidth, ...
    'MarkerSize', style.markerSize, ...
    'CapSize', 3, ...
    'DisplayName', 'RSVD');

gnError = errorbar(matrixErrorAxis, rank, ...
    matrixData.GN_RelErrMean, matrixData.GN_RelErrStd, ...
    'Color', style.methods.secondary.color, ...
    'LineStyle', style.methods.secondary.line, ...
    'Marker', style.methods.secondary.marker, ...
    'LineWidth', style.lineWidth, ...
    'MarkerSize', style.markerSize, ...
    'CapSize', 3, ...
    'DisplayName', 'GN');

xlabel(matrixErrorAxis, 'Target rank $r$', 'Interpreter', 'latex');
ylabel(matrixErrorAxis, ...
    '$\Vert A-\widehat A_r\Vert_F/\Vert A\Vert_F$', ...
    'Interpreter', 'latex');
xticks(matrixErrorAxis, [5, 20, 40, 80, 120]);

matrixTimeAxis = nexttile(matrixLayout);
matrixTimeAxis.YScale = 'log';
hold(matrixTimeAxis, 'on');

svdTime = yline(matrixTimeAxis, matrixData.SVD_Time(1), ...
    style.methods.baseline.line, ...
    'Color', style.methods.baseline.color, ...
    'LineWidth', style.lineWidth, ...
    'DisplayName', 'full economy SVD');

errorbar(matrixTimeAxis, rank, ...
    matrixData.RSVD_TimeMean, matrixData.RSVD_TimeStd, ...
    'Color', style.methods.primary.color, ...
    'LineStyle', style.methods.primary.line, ...
    'Marker', style.methods.primary.marker, ...
    'LineWidth', style.lineWidth, ...
    'MarkerSize', style.markerSize, ...
    'CapSize', 3, ...
    'DisplayName', 'RSVD');

errorbar(matrixTimeAxis, rank, ...
    matrixData.GN_TimeMean, matrixData.GN_TimeStd, ...
    'Color', style.methods.secondary.color, ...
    'LineStyle', style.methods.secondary.line, ...
    'Marker', style.methods.secondary.marker, ...
    'LineWidth', style.lineWidth, ...
    'MarkerSize', style.markerSize, ...
    'CapSize', 3, ...
    'DisplayName', 'GN');

xlabel(matrixTimeAxis, 'Target rank $r$', 'Interpreter', 'latex');
ylabel(matrixTimeAxis, 'Measured time (s)', 'Interpreter', 'latex');
xticks(matrixTimeAxis, [5, 20, 40, 80, 120]);

matrixLegend = legend(matrixErrorAxis, ...
    [svdError, rsvdError, gnError], ...
    {'truncated SVD', 'RSVD', 'GN'}, ...
    'Orientation', 'horizontal', 'NumColumns', 3);
matrixLegend.Layout.Tile = 'north';

apply_numerical_figure_style(matrixFigure, ...
    'WidthCm', 15.8, 'HeightCm', 6.4, 'Grid', true);
svdTime.LineWidth = style.referenceLineWidth;

export_numerical_figure(matrixFigure, fullfile( ...
    figureFolder, 'controlled_matrix_randomized_compression'), ...
    'WritePNG', true, 'WriteFIG', true);
close(matrixFigure);

%% Tensor: approximation error and directly measured method time
