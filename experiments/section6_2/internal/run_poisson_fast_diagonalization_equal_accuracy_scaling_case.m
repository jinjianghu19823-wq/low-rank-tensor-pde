function run_poisson_fast_diagonalization_equal_accuracy_scaling_case(N, methodIndex, repeatIndex, orderPosition, configOverride)
%RUN_POISSON_FAST_DIAGONALIZATION_EQUAL_ACCURACY_SCALING_CASE
% Warm and measure one method in a protected fresh MATLAB process.
%
% Thesis/experiment notation (Section 6.2):
%   N                           <->  mode size
%   h                           <->  1/(N+1)
%   A1                          <->  A_1=h^(-2)tridiag(-1,2,-1)
%   gaussianVector             <->  one factor of the rank-one \mathcal B_0
%   preconditionerRank         <->  selected equal Tucker rank r of D_r
%   maximumMultilinearRank     <->  \boldsymbol R=(N,N,N), so no extra cap
%   methodIndex                <->  1 full, 2 fixed Tucker, 3 relaxed Tucker
%   repeatIndex, orderPosition <->  balanced timing-design indices
% The older function name says equal_accuracy; configOverride supplies the
% current fixed-four-step protocol and its external 10^(-6) reference.


%% 1. Validate the frozen case identity and protect its outputs

experimentFolder = fileparts(mfilename('fullpath'));
matlabFolder = fileparts(experimentFolder);
repositoryFolder = fileparts(fileparts(matlabFolder));
addpath(repositoryFolder);
add_toolboxes();

if nargin < 5
    config = ...
        poisson_fast_diagonalization_equal_accuracy_scaling_config();
else
    config = configOverride;
end

if ~isscalar(N) || N ~= round(N) || ...
        ~ismember(N, config.candidateN)
    error('N must be one of the frozen grid sizes.');
end

if isfield(config, 'reusedN') && isfinite(config.reusedN) && ...
        N == config.reusedN
    error('The protected N=300 timing dataset is reused, not rerun.');
end

if ~isscalar(methodIndex) || ...
        methodIndex ~= round(methodIndex) || ...
        methodIndex < 1 || methodIndex > numel(config.methodIds)
    error('methodIndex must select one frozen method.');
end

if ~isscalar(repeatIndex) || ...
        repeatIndex ~= round(repeatIndex) || ...
        repeatIndex < 1 || ...
        repeatIndex > config.numberOfMeasuredRepeats
    error('repeatIndex must select one frozen measured repeat.');
end

if ~isscalar(orderPosition) || ...
        orderPosition ~= round(orderPosition) || ...
        orderPosition < 1 || orderPosition > 3
    error('orderPosition must be 1, 2, or 3.');
end

assert(config.balancedOrder(repeatIndex, orderPosition) == methodIndex, ...
    'The requested case does not follow the frozen balanced order.');

gridIndex = find(config.candidateN == N, 1);
preconditionerRank = config.preconditionerTuckerRanks(gridIndex);
methodId = char(config.methodIds(methodIndex));
methodName = config.methodNames(methodIndex);

processedFolder = fullfile(repositoryFolder, 'experiments', 'processed');
rawFolder = fullfile(repositoryFolder, 'experiments', 'raw');

if ~isfolder(processedFolder)
    mkdir(processedFolder);
end

if ~isfolder(rawFolder)
    mkdir(rawFolder);
end

casePrefix = sprintf( ...
    '%s_n%d_repeat_%02d_position_%d_method_%s', ...
    char(config.outputPrefix), N, repeatIndex, orderPosition, methodId);
summaryPath = fullfile( ...
    processedFolder, [casePrefix, '_summary.csv']);
rawPath = fullfile(rawFolder, [casePrefix, '.mat']);

if isfile(summaryPath) || isfile(rawPath)
    error('The protected scaling-case output already exists.');
end


%% 2. Check the declared full-format memory budget

numberOfUnknowns = N^config.numberOfModes;
preallocatedFullBasisGiB = ...
    (config.maximumIteration + 1) * ...
    numberOfUnknowns * 8 / 2^30;
estimatedPeakFullArrayGiB = ...
    config.estimatedPeakFullArrayCopies * ...
    numberOfUnknowns * 8 / 2^30;

if methodIndex == 1
    assert(preallocatedFullBasisGiB <= ...
        config.maximumPreallocatedFullBasisGiB, ...
        'The delayed full basis exceeds the declared safety limit.');
    assert(estimatedPeakFullArrayGiB <= ...
        config.maximumEstimatedFullArrayGiB, ...
        'The conservative full-array estimate exceeds the safety limit.');
end


%% 3. Construct the common Poisson problem and selected preconditioner

h = 1 / (N + 1);
onesVector = ones(N, 1);
A1 = spdiags([-onesVector, 2 * onesVector, -onesVector], -1:1, N, N) / h^2;

gridPoints = (1:N).' / (N + 1);
gaussianVector = exp(-config.gaussianExponent * (gridPoints - 1/2).^2);

preconditionerSetupTimer = tic;
[preconditioner, preconditionerInfo] = build_poisson_fast_diagonalization_tucker_preconditioner(A1, preconditionerRank);
preconditionerSetupTimeSec = toc(preconditionerSetupTimer);

assert(preconditionerInfo.is_positive_definite, ...
    'The selected preconditioner is not positive definite.');
assert(preconditionerInfo.spectral_delta <= ...
    config.maximumPreconditionerSpectralDelta, ...
    'The selected preconditioner violates the spectral-quality rule.');

maximumMultilinearRank = N * ones(1, config.numberOfModes);
methodData = build_method_data(methodIndex, config, A1, gaussianVector, preconditioner, maximumMultilinearRank);


%% 4. Warm once, then perform the protected measurement

fprintf('\nN=%d, repeat %d, position %d: %s\n', ...
    N, repeatIndex, orderPosition, char(methodName));
fprintf('Preconditioner rank %d, delta %.3e, kappa %.6f\n', ...
    preconditionerRank, preconditionerInfo.spectral_delta, ...
    preconditionerInfo.condition_number);
fprintf('Warm-up solve...\n');

warmupCallTimer = tic;
warmupInfo = execute_method(methodIndex, config, methodData, maximumMultilinearRank);
warmupCallTimeSec = toc(warmupCallTimer);
warmupSummary = summarise_method(methodIndex, config, methodData, warmupInfo);

fprintf('Measured solve...\n');

measuredCallTimer = tic;
measuredInfo = execute_method(methodIndex, config, methodData, maximumMultilinearRank);
measuredCallTimeSec = toc(measuredCallTimer);
measuredSummary = summarise_method(methodIndex, config, methodData, measuredInfo);


%% 5. Save both outcomes, including unsuccessful target checks

phase = ["warmup"; "measured"];
measured = [false; true];
NColumn = repmat(N, 2, 1);
numberOfUnknownsColumn = repmat(numberOfUnknowns, 2, 1);
preconditionerRankColumn = repmat(preconditionerRank, 2, 1);
preconditionerSpectralDelta = ...
    repmat(preconditionerInfo.spectral_delta, 2, 1);
preconditionerConditionNumber = ...
    repmat(preconditionerInfo.condition_number, 2, 1);
preconditionerSetupTime = repmat(preconditionerSetupTimeSec, 2, 1);
methodIndexColumn = repmat(methodIndex, 2, 1);
methodIdColumn = repmat(string(methodId), 2, 1);
methodNameColumn = repmat(methodName, 2, 1);
repeatIndexColumn = repmat(repeatIndex, 2, 1);
orderPositionColumn = repmat(orderPosition, 2, 1);

iterations = [warmupSummary.iterations; measuredSummary.iterations];
passed = [warmupSummary.passed; measuredSummary.passed];
stopReason = [ ...
    warmupSummary.stop_reason; measuredSummary.stop_reason];
finalOriginalResidual = [ ...
    warmupSummary.final_original_residual; ...
    measuredSummary.final_original_residual];
finalComputedPreconditionedResidual = [ ...
    warmupSummary.final_computed_preconditioned_residual; ...
    measuredSummary.final_computed_preconditioned_residual];
finalIndependentPreconditionedResidual = [ ...
    warmupSummary.final_independent_preconditioned_residual; ...
    measuredSummary.final_independent_preconditioned_residual];
preconditionedResidualGap = [ ...
    warmupSummary.preconditioned_residual_gap; ...
    measuredSummary.preconditioned_residual_gap];
solverTimeSec = [ ...
    warmupSummary.solver_time_sec; measuredSummary.solver_time_sec];
diagnosticTimeSec = [ ...
    warmupSummary.diagnostic_time_sec; ...
    measuredSummary.diagnostic_time_sec];
wallTimeSec = [ ...
    warmupSummary.wall_time_sec; measuredSummary.wall_time_sec];
outerCallTimeSec = [warmupCallTimeSec; measuredCallTimeSec];
basisStorageMiB = [ ...
    warmupSummary.basis_storage_mib; ...
    measuredSummary.basis_storage_mib];
maximumBasisRank = [ ...
    warmupSummary.maximum_basis_rank; ...
    measuredSummary.maximum_basis_rank];
solutionMode1Rank = [ ...
    warmupSummary.solution_mode_1_rank; ...
    measuredSummary.solution_mode_1_rank];
solutionMode2Rank = [ ...
    warmupSummary.solution_mode_2_rank; ...
    measuredSummary.solution_mode_2_rank];
solutionMode3Rank = [ ...
    warmupSummary.solution_mode_3_rank; ...
    measuredSummary.solution_mode_3_rank];
rankCapActive = [ ...
    warmupSummary.rank_cap_active; ...
    measuredSummary.rank_cap_active];
maximumOperatorErrorRatio = [ ...
    warmupSummary.maximum_operator_error_ratio; ...
    measuredSummary.maximum_operator_error_ratio];
maximumOrthogonalisationErrorRatio = [ ...
    warmupSummary.maximum_orthogonalisation_error_ratio; ...
    measuredSummary.maximum_orthogonalisation_error_ratio];
preallocatedFullBasisGiBColumn = ...
    repmat(preallocatedFullBasisGiB, 2, 1);
estimatedPeakFullArrayGiBColumn = ...
    repmat(estimatedPeakFullArrayGiB, 2, 1);

summaryTable = table( ...
    phase, measured, NColumn, numberOfUnknownsColumn, ...
    preconditionerRankColumn, preconditionerSpectralDelta, ...
    preconditionerConditionNumber, preconditionerSetupTime, ...
    methodIndexColumn, methodIdColumn, methodNameColumn, ...
    repeatIndexColumn, orderPositionColumn, ...
    iterations, passed, stopReason, ...
    finalOriginalResidual, ...
    finalComputedPreconditionedResidual, ...
    finalIndependentPreconditionedResidual, ...
    preconditionedResidualGap, ...
    solverTimeSec, diagnosticTimeSec, wallTimeSec, ...
    outerCallTimeSec, basisStorageMiB, maximumBasisRank, ...
    solutionMode1Rank, solutionMode2Rank, solutionMode3Rank, ...
    rankCapActive, maximumOperatorErrorRatio, ...
    maximumOrthogonalisationErrorRatio, ...
    preallocatedFullBasisGiBColumn, ...
    estimatedPeakFullArrayGiBColumn, ...
    'VariableNames', { ...
        'phase', 'measured', 'N', 'number_of_unknowns', ...
        'preconditioner_tucker_rank', ...
        'preconditioner_spectral_delta', ...
        'preconditioner_condition_number', ...
        'preconditioner_setup_time_sec', ...
        'method_index', 'method_id', 'method_name', ...
        'repeat_index', 'order_position', ...
        'iterations', 'passed', 'stop_reason', ...
        'final_original_true_relative_residual', ...
        'final_computed_preconditioned_relative_residual', ...
        'final_independent_preconditioned_relative_residual', ...
        'preconditioned_residual_gap', ...
        'solver_time_sec', 'diagnostic_time_sec', ...
        'wall_time_sec', 'outer_call_time_sec', ...
        'basis_storage_mib', 'maximum_basis_rank', ...
        'solution_mode_1_rank', 'solution_mode_2_rank', ...
        'solution_mode_3_rank', 'rank_cap_active', ...
        'maximum_operator_error_to_tolerance_ratio', ...
        'maximum_orthogonalisation_error_to_tolerance_ratio', ...
        'preallocated_full_basis_gib', ...
        'conservative_full_array_estimate_gib'});

writetable(summaryTable, summaryPath);
save(rawPath, ...
    'config', 'N', 'methodIndex', 'repeatIndex', 'orderPosition', ...
    'preconditionerInfo', 'warmupInfo', 'measuredInfo', ...
    'summaryTable');

fprintf('Measured original residual: %.3e\n', ...
    measuredSummary.final_original_residual);
fprintf('Measured solver time: %.3f s\n', ...
    measuredSummary.solver_time_sec);
fprintf('Measured basis storage: %.3f MiB\n', ...
    measuredSummary.basis_storage_mib);
fprintf('Measured contract passed: %d\n', measuredSummary.passed);

end


function methodData = build_method_data( ...
    methodIndex, config, A1, gaussianVector, ...
    preconditioner, maximumMultilinearRank)
%BUILD_METHOD_DATA Allocate only the representation used by one method.

N = length(gaussianVector);

if methodIndex == 1

    methodData.b = kron( ...
        gaussianVector, kron(gaussianVector, gaussianVector));
    methodData.x0 = zeros(N^3, 1);
    inverseMultiplier = ...
        double(full(preconditioner.inverse_eigenvalue_tensor));
    methodData.operator_function = @(x) ...
        poisson_action_full_vector_3d(x, A1, N);
    methodData.preconditioner_function = @(x) ...
        apply_poisson_fast_diagonalization_full_preconditioner( ...
            x, inverseMultiplier);

else

    methodData.F = ttensor(tensor(1, [1, 1, 1]), ...
        {gaussianVector, gaussianVector, gaussianVector});
    methodData.U0 = 0 * methodData.F;
    methodData.operator_function = @(U, tolerance, maximumRanks) ...
        poisson_action_tucker(U, A1, tolerance, maximumRanks);
    methodData.preconditioner_function = ...
        @(Y, tolerance, maximumRanks) ...
        apply_poisson_fast_diagonalization_tucker_preconditioner( ...
            Y, preconditioner, tolerance, maximumRanks);
    methodData.original_residual_function = @(U) ...
        true_residual_tucker_poisson(U, methodData.F, A1);
    methodData.preconditioned_residual_function = @(U) ...
        preconditioned_residual_norm_tucker_poisson_fast_diagonalization( ...
            U, methodData.F, A1, preconditioner, ...
            config.diagnosticTolerance);
    methodData.maximum_multilinear_rank = maximumMultilinearRank;

end

end


function info = execute_method( ...
    methodIndex, config, methodData, maximumMultilinearRank)
%EXECUTE_METHOD Run one warmed or measured solve.

if methodIndex == 1

    [~, info] = gmres_left_preconditioned_full_fixed_cycle( ...
        methodData.operator_function, ...
        methodData.preconditioner_function, ...
        methodData.b, methodData.x0, ...
        config.maximumIteration, ...
        config.originalTrueResidualTarget, false);

elseif methodIndex == 2

    [~, info] = tucker_gmres_left_preconditioned_fixed( ...
        methodData.operator_function, ...
        methodData.preconditioner_function, ...
        methodData.F, methodData.U0, ...
        config.maximumIteration, ...
        config.internalPreconditionedStoppingTolerance, ...
        config.fixedRecompressionTolerance, ...
        methodData.original_residual_function, ...
        methodData.preconditioned_residual_function, ...
        false, config.maximumTuckerBasisEntries, ...
        maximumMultilinearRank);

else

    [~, info] = tucker_gmres_left_preconditioned_capped_relaxed( ...
        methodData.operator_function, ...
        methodData.preconditioner_function, ...
        methodData.F, methodData.U0, ...
        config.maximumIteration, ...
        config.internalPreconditionedStoppingTolerance, ...
        config.relaxationErrorBudget, ...
        config.maximumRelaxedTolerance, ...
        methodData.original_residual_function, ...
        methodData.preconditioned_residual_function, ...
        false, config.maximumTuckerBasisEntries, ...
        maximumMultilinearRank);

end

end


function summary = summarise_method( ...
    methodIndex, config, methodData, info)
%SUMMARISE_METHOD Convert one solver result to common checked metrics.

summary.iterations = info.iterations;
summary.stop_reason = string(info.stop_reason);

if methodIndex == 1

    summary.final_original_residual = ...
        info.original_true_relative_residual;
    summary.final_computed_preconditioned_residual = ...
        info.computed_preconditioned_relative_residual(end);
    summary.final_independent_preconditioned_residual = ...
        info.true_preconditioned_relative_residual;
    summary.preconditioned_residual_gap = ...
        info.preconditioned_residual_gap;
    summary.basis_storage_mib = ...
        info.number_of_basis_vectors * numel(methodData.b) * 8 / 2^20;
    summary.maximum_basis_rank = NaN;
    summary.solution_mode_1_rank = NaN;
    summary.solution_mode_2_rank = NaN;
    summary.solution_mode_3_rank = NaN;
    summary.rank_cap_active = false;
    summary.maximum_operator_error_ratio = NaN;
    summary.maximum_orthogonalisation_error_ratio = NaN;

    summary.passed = ...
        info.iterations == config.maximumIteration && ...
        info.converged && ~info.breakdown && ...
        summary.preconditioned_residual_gap < 1e-10;

else

    summary.final_original_residual = ...
        info.true_relative_residual(end);
    summary.final_computed_preconditioned_residual = ...
        info.computed_preconditioned_relative_residual(end);
    summary.final_independent_preconditioned_residual = ...
        info.true_preconditioned_relative_residual(end);
    summary.preconditioned_residual_gap = ...
        info.preconditioned_residual_gap;
    summary.basis_storage_mib = ...
        info.peak_basis_storage_entries * 8 / 2^20;
    summary.maximum_basis_rank = ...
        max(info.basis_ranks, [], 'all');
    summary.solution_mode_1_rank = info.solution_ranks(1);
    summary.solution_mode_2_rank = info.solution_ranks(2);
    summary.solution_mode_3_rank = info.solution_ranks(3);
    summary.rank_cap_active = info.rank_cap_active;
    summary.maximum_operator_error_ratio = max([0; ...
        info.operator_product_maximum_local_recompression_error ./ ...
        info.eta]);
    summary.maximum_orthogonalisation_error_ratio = max([0; ...
        info.orthogonalisation_maximum_local_recompression_error ./ ...
        info.eta]);

    subdiagonal = diag(info.H, -1);
    numericalBreakdown = any(subdiagonal == 0);

    summary.passed = ...
        info.iterations == config.maximumIteration && ...
        summary.final_original_residual <= ...
        config.originalTrueResidualTarget && ...
        ~numericalBreakdown && ...
        ~info.rank_cap_active && ...
        ~info.stopped_for_basis_memory && ...
        summary.maximum_operator_error_ratio <= 1 + 1e-10 && ...
        summary.maximum_orthogonalisation_error_ratio <= 1 + 1e-10;

end

summary.solver_time_sec = info.solver_time_sec;
summary.diagnostic_time_sec = info.diagnostic_time_sec;
summary.wall_time_sec = info.wall_time_sec;

end
