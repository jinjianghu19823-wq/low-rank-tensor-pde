function plot_poisson_fast_diagonalization_fixed_iteration_scaling()
%PLOT_POISSON_FAST_DIAGONALIZATION_FIXED_ITERATION_SCALING
% Consolidate the four-step study and create its three evidence figures.
%
% Thesis/experiment notation (Section 6.2):
%   N                              <->  mode size
%   finalResiduals                 <->  original true relative residuals
%   solverTimes                    <->  solver-only measured times
%   basis_storage_mib              <->  active Krylov-basis storage
%   maximum_basis_rank             <->  largest Tucker basis rank
%   preconditioner_spectral_delta  <->  spectral defect delta


%% 1. Locate and validate every protected timing case

experimentFolder = fileparts(mfilename('fullpath'));
matlabFolder = fileparts(experimentFolder);
repositoryFolder = fileparts(matlabFolder);
addpath(repositoryFolder);
setup();
processedFolder = fullfile(repositoryFolder, 'experiments', 'processed');
figureFolder = fullfile(repositoryFolder, 'experiments', 'figures');

if ~isfolder(figureFolder)
    mkdir(figureFolder);
end

config = ...
    poisson_fast_diagonalization_fixed_iteration_scaling_config();
prefix = char(config.outputPrefix);

allRuns = table();

for N = config.candidateN
    for repeatIndex = 1:config.numberOfMeasuredRepeats
        for orderPosition = 1:3

            methodIndex = ...
                config.balancedOrder(repeatIndex, orderPosition);
            methodId = char(config.methodIds(methodIndex));
            casePrefix = sprintf( ...
                '%s_n%d_repeat_%02d_position_%d_method_%s', ...
                prefix, N, repeatIndex, orderPosition, methodId);
            summaryPath = fullfile( ...
                processedFolder, [casePrefix, '_summary.csv']);

            assert(isfile(summaryPath), ...
                'A protected timing summary is missing: %s', ...
                summaryPath);
            nextRows = readtable(summaryPath);
            assert(height(nextRows) == 2, ...
                'Each timing case must contain warm-up and measured rows.');
            allRuns = append_table(allRuns, nextRows);

        end
    end
end

allRuns = sortrows( ...
    allRuns, {'N', 'repeat_index', 'order_position', 'measured'});
measuredRuns = allRuns(logical(allRuns.measured), :);

expectedMeasuredRuns = ...
    numel(config.candidateN) * ...
    config.numberOfMeasuredRepeats * numel(config.methodIds);

assert(height(measuredRuns) == expectedMeasuredRuns, ...
    'The measured table has the wrong number of rows.');
assert(height(allRuns) == 2 * expectedMeasuredRuns, ...
    'The combined table has the wrong number of rows.');
assert(all(measuredRuns.iterations == config.maximumIteration), ...
    'Every measured method must complete four Arnoldi steps.');
assert(all(isfinite( ...
    measuredRuns.final_original_true_relative_residual)), ...
    'Every measured run must have a finite original residual.');
assert(~any(measuredRuns.rank_cap_active), ...
    'A Tucker rank cap became active.');

allRunsPath = fullfile( ...
    processedFolder, [prefix, '_all_runs.csv']);
measuredRunsPath = fullfile( ...
    processedFolder, [prefix, '_measured_runs.csv']);
writetable(allRuns, allRunsPath);
writetable(measuredRuns, measuredRunsPath);


%% 2. Summarise timing, accuracy, storage, and rank

methodSummary = table();

for N = config.candidateN
    for methodIndex = 1:numel(config.methodIds)

        methodRows = measuredRuns( ...
            measuredRuns.N == N & ...
            measuredRuns.method_index == methodIndex, :);

        assert(height(methodRows) == ...
            config.numberOfMeasuredRepeats, ...
            'Each grid-method pair requires three repetitions.');

        solverTimes = methodRows.solver_time_sec;
        finalResiduals = ...
            methodRows.final_original_true_relative_residual;
        targetHit = ...
            finalResiduals <= config.originalTrueResidualTarget;

        nextRow = table( ...
            N, N^config.numberOfModes, ...
            methodRows.preconditioner_tucker_rank(1), ...
            methodRows.preconditioner_spectral_delta(1), ...
            methodRows.preconditioner_condition_number(1), ...
            methodIndex, config.methodIds(methodIndex), ...
            config.methodNames(methodIndex), ...
            height(methodRows), sum(targetHit), all(targetHit), ...
            median(finalResiduals), min(finalResiduals), ...
            max(finalResiduals), ...
            median(solverTimes), min(solverTimes), max(solverTimes), ...
            median(methodRows.basis_storage_mib), ...
            median(methodRows.maximum_basis_rank, 'omitnan'), ...
            'VariableNames', { ...
                'N', 'number_of_unknowns', ...
                'preconditioner_tucker_rank', ...
                'preconditioner_spectral_delta', ...
                'preconditioner_condition_number', ...
                'method_index', 'method_id', 'method_name', ...
                'number_of_repeats', 'target_hits', ...
                'all_target_hits', ...
                'median_final_original_true_relative_residual', ...
                'minimum_final_original_true_relative_residual', ...
                'maximum_final_original_true_relative_residual', ...
                'median_solver_time_sec', ...
                'minimum_solver_time_sec', ...
                'maximum_solver_time_sec', ...
                'basis_storage_mib', 'maximum_basis_rank'});

        methodSummary = append_table(methodSummary, nextRow);

    end
end

summaryPath = fullfile( ...
    processedFolder, [prefix, '_method_summary.csv']);
writetable(methodSummary, summaryPath);

companionTable = methodSummary(:, { ...
    'N', 'number_of_unknowns', 'method_name', ...
    'number_of_repeats', 'target_hits', ...
    'median_final_original_true_relative_residual', ...
    'median_solver_time_sec', 'minimum_solver_time_sec', ...
    'maximum_solver_time_sec', ...
    'basis_storage_mib', 'maximum_basis_rank'});
companionPath = fullfile( ...
    processedFolder, [prefix, '_companion_table.csv']);
writetable(companionTable, companionPath);


%% 3. Combine the separately evaluated residual and rank histories

residualHistory = table();
rankHistory = table();

for N = config.representativeN

    casePrefix = sprintf('%s_n%d_diagnostic', prefix, N);
    residualPath = fullfile( ...
        processedFolder, [casePrefix, '_residual_history.csv']);
    rankPath = fullfile( ...
        processedFolder, [casePrefix, '_rank_history.csv']);

    assert(isfile(residualPath), ...
        'A diagnostic residual history is missing.');
    assert(isfile(rankPath), ...
        'A diagnostic rank history is missing.');

    residualHistory = append_table( ...
        residualHistory, readtable(residualPath));
    rankHistory = append_table(rankHistory, readtable(rankPath));

end

assert(all(residualHistory.iteration >= 0 & ...
    residualHistory.iteration <= config.maximumIteration), ...
    'The residual iteration indices are invalid.');
assert(all(rankHistory.iteration >= 0 & ...
    rankHistory.iteration <= config.maximumIteration), ...
    'The rank iteration indices are invalid.');

writetable(residualHistory, fullfile( ...
    processedFolder, [prefix, '_residual_history.csv']));
writetable(rankHistory, fullfile( ...
    processedFolder, [prefix, '_rank_history.csv']));


%% 4. Create the residual-versus-iteration figure

S = numerical_plot_style();
methodStyles = [ ...
    S.methods.baseline; ...
    S.methods.primary; ...
    S.methods.secondary];

residualFigure = figure('Visible', 'off', 'Color', 'white');
residualLayout = tiledlayout( ...
    residualFigure, 1, numel(config.representativeN), ...
    'TileSpacing', 'compact', 'Padding', 'compact');

for gridIndex = 1:numel(config.representativeN)

    N = config.representativeN(gridIndex);
    residualAxes = nexttile(residualLayout);
    hold(residualAxes, 'on');

    for methodIndex = 1:numel(config.methodIds)

        rows = residualHistory( ...
            residualHistory.N == N & ...
            residualHistory.method_index == methodIndex, :);
        rows = sortrows(rows, 'iteration');
        style = methodStyles(methodIndex);

        semilogy(residualAxes, rows.iteration, ...
            rows.original_true_relative_residual, ...
            'Color', style.color, ...
            'LineStyle', style.line, ...
            'Marker', style.marker, ...
            'MarkerFaceColor', 'white', ...
            'DisplayName', char(config.methodNames(methodIndex)));

    end

    yline(residualAxes, config.originalTrueResidualTarget, ...
        '--', '$10^{-6}$', ...
        'Color', S.colors.gray, ...
        'HandleVisibility', 'off', ...
        'LabelHorizontalAlignment', 'left');
    set(residualAxes, 'YScale', 'log');
    xlabel(residualAxes, 'Arnoldi iteration $j$');
    title(residualAxes, sprintf('$N=%d$', N));
    xlim(residualAxes, [0, config.maximumIteration]);
    ylim(residualAxes, [1e-10, 2]);
    xticks(residualAxes, 0:config.maximumIteration);

    if gridIndex == 1
        ylabel(residualAxes, ...
            '$\Vert b-Ax_j\Vert_2/\Vert b\Vert_2$');
        residualLegend = legend( ...
            residualAxes, 'Orientation', 'horizontal');
        residualLegend.Layout.Tile = 'south';
    end

end

apply_numerical_figure_style( ...
    residualFigure, 'WidthCm', 15.8, 'HeightCm', 6.8);
export_numerical_figure( ...
    residualFigure, fullfile( ...
        figureFolder, [prefix, '_residual_history']), ...
    'WritePNG', true, 'WriteFIG', true);
close(residualFigure);


%% 5. Create the solver-time scaling figure

timeFigure = figure('Visible', 'off', 'Color', 'white');
timeAxes = axes(timeFigure);
hold(timeAxes, 'on');

for methodIndex = 1:numel(config.methodIds)

    rows = methodSummary(methodSummary.method_index == methodIndex, :);
    style = methodStyles(methodIndex);
    lowerError = rows.median_solver_time_sec - ...
        rows.minimum_solver_time_sec;
    upperError = rows.maximum_solver_time_sec - ...
        rows.median_solver_time_sec;

    errorbar(timeAxes, rows.N, rows.median_solver_time_sec, ...
        lowerError, upperError, ...
        'Color', style.color, ...
        'LineStyle', style.line, ...
        'Marker', style.marker, ...
        'MarkerFaceColor', 'white', ...
        'DisplayName', char(config.methodNames(methodIndex)));

end

set(timeAxes, 'YScale', 'log');
xlabel(timeAxes, 'Grid size $N$');
ylabel(timeAxes, 'Solver time for four Arnoldi steps (s)');
xticks(timeAxes, config.candidateN);
legend(timeAxes, 'Location', 'northwest');

apply_numerical_figure_style( ...
    timeFigure, 'WidthCm', 15.8, 'HeightCm', 8.2);
export_numerical_figure( ...
    timeFigure, fullfile( ...
        figureFolder, [prefix, '_solver_time_scaling']), ...
    'WritePNG', true, 'WriteFIG', true);
close(timeFigure);


%% 6. Create the maximum-rank-versus-iteration figure

rankFigure = figure('Visible', 'off', 'Color', 'white');
rankLayout = tiledlayout( ...
    rankFigure, 1, numel(config.representativeN), ...
    'TileSpacing', 'compact', 'Padding', 'compact');

for gridIndex = 1:numel(config.representativeN)

    N = config.representativeN(gridIndex);
    rankAxes = nexttile(rankLayout);
    hold(rankAxes, 'on');

    for methodIndex = 2:3

        rows = rankHistory( ...
            rankHistory.N == N & ...
            rankHistory.method_index == methodIndex, :);
        rows = sortrows(rows, 'iteration');
        style = methodStyles(methodIndex);

        plot(rankAxes, rows.iteration, ...
            rows.maximum_basis_rank_to_iteration, ...
            'Color', style.color, ...
            'LineStyle', style.line, ...
            'Marker', style.marker, ...
            'MarkerFaceColor', 'white', ...
            'DisplayName', char(config.methodNames(methodIndex)));

    end

    xlabel(rankAxes, 'Arnoldi iteration $j$');
    title(rankAxes, sprintf('$N=%d$', N));
    xlim(rankAxes, [0, config.maximumIteration]);
    ylim(rankAxes, [0, 110]);
    xticks(rankAxes, 0:config.maximumIteration);
    yticks(rankAxes, 0:20:100);

    if gridIndex == 1
        ylabel(rankAxes, 'Maximum Tucker basis rank');
        rankLegend = legend( ...
            rankAxes, 'Orientation', 'horizontal');
        rankLegend.Layout.Tile = 'south';
    end

end

apply_numerical_figure_style( ...
    rankFigure, 'WidthCm', 15.8, 'HeightCm', 6.8);
export_numerical_figure( ...
    rankFigure, fullfile( ...
        figureFolder, [prefix, '_maximum_rank_history']), ...
    'WritePNG', true, 'WriteFIG', true);
close(rankFigure);


%% 7. Report the generated evidence

fprintf('Saved timing summary: %s\n', summaryPath);
fprintf('Saved companion table: %s\n', companionPath);
fprintf('Saved three fixed-iteration figures with prefix: %s\n', prefix);

end


function outputTable = append_table(outputTable, nextRows)
%APPEND_TABLE Append rows while preserving the first table's types.

if isempty(outputTable)
    outputTable = nextRows;
else
    outputTable = [outputTable; nextRows];
end

end
